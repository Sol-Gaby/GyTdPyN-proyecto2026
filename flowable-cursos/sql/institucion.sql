-- Fase 1: iniciar la sesión en POSTGRES_DB, la base del motor.
BEGIN;
CREATE TABLE IF NOT EXISTS cursos_pendientes (
    revision bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proceso_id varchar(128) NOT NULL,
    codigo_empresa varchar(100) NOT NULL,
    nombre_empresa text NOT NULL,
    nombre_curso text NOT NULL,
    descripcion text NOT NULL,
    programa text,
    presupuesto numeric CHECK (presupuesto >= 0),
    fechas_posibles text,
    fecha_inicio timestamp with time zone,
    informe text,
    estado varchar(24) NOT NULL
);

-- Los datos de solicitud y documentos viajan por la misma cola transaccional.
ALTER TABLE cursos_pendientes ADD COLUMN IF NOT EXISTS solicitud_web text;
ALTER TABLE cursos_pendientes ADD COLUMN IF NOT EXISTS documento_tipo varchar(12);
ALTER TABLE cursos_pendientes ADD COLUMN IF NOT EXISTS habilitar_empresa boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS referencias_portal (
    referencia varchar(50) PRIMARY KEY
);
ALTER TABLE cursos_pendientes ADD COLUMN IF NOT EXISTS solicitud_referencia varchar(50);
CREATE INDEX IF NOT EXISTS cursos_pendientes_proceso_idx ON cursos_pendientes(proceso_id, revision);
COMMIT;

