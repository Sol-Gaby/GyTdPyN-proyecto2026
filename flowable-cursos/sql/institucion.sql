SELECT 'CREATE DATABASE institucion_cursos'
WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = 'institucion_cursos') \gexec

\connect institucion_cursos

BEGIN;

CREATE TABLE IF NOT EXISTS empresas (
    codigo varchar(100) PRIMARY KEY,
    nombre text NOT NULL
);

CREATE TABLE IF NOT EXISTS cursos (
    proceso_id varchar(128) PRIMARY KEY,
    empresa_codigo varchar(100) NOT NULL REFERENCES empresas(codigo),
    nombre text NOT NULL,
    descripcion text NOT NULL,
    programa text,
    presupuesto numeric CHECK (presupuesto >= 0),
    fechas_posibles text,
    fecha_inicio timestamp with time zone,
    informe text,
    estado varchar(24) NOT NULL CHECK (estado IN (
        'EN_TRAMITE', 'FINALIZADO', 'CANCELADO', 'RECHAZADO', 'SIN_RESPUESTA', 'NO_VIABLE')),
    revision bigint NOT NULL
);

CREATE INDEX IF NOT EXISTS cursos_empresa_idx ON cursos(empresa_codigo);

ALTER TABLE cursos ADD COLUMN IF NOT EXISTS solicitud_web text;
ALTER TABLE empresas ADD COLUMN IF NOT EXISTS acceso_habilitado boolean NOT NULL DEFAULT false;
ALTER TABLE empresas ADD COLUMN IF NOT EXISTS clave_portal text;

CREATE TABLE IF NOT EXISTS documentos_curso (
    proceso_id varchar(128) NOT NULL REFERENCES cursos(proceso_id),
    tipo varchar(12) NOT NULL CHECK (tipo IN ('PROPUESTA', 'INFORME')),
    revision bigint NOT NULL,
    contenido bytea NOT NULL,
    PRIMARY KEY (proceso_id, tipo, revision)
);

ALTER TABLE cursos ADD COLUMN IF NOT EXISTS solicitud_referencia varchar(50);
CREATE UNIQUE INDEX IF NOT EXISTS cursos_solicitud_idx ON cursos(solicitud_referencia);

