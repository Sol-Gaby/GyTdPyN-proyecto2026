CREATE TABLE IF NOT EXISTS empresas (
    codigo varchar(100) PRIMARY KEY,
    nombre text NOT NULL
);

CREATE TABLE IF NOT EXISTS cursos (
    proceso_id varchar(128) PRIMARY KEY,
    empresa_codigo varchar(100) NOT NULL REFERENCES empresas(codigo),
    nombre text NOT NULL,
    descripcion text NOT NULL,
    programa text,
    presupuesto numeric CHECK (presupuesto >= 0),
    fechas_posibles text,
    fecha_inicio timestamp with time zone,
    informe text,
    estado varchar(24) NOT NULL CHECK (estado IN (
        'EN_TRAMITE', 'FINALIZADO', 'CANCELADO', 'RECHAZADO', 'SIN_RESPUESTA', 'NO_VIABLE')),
    revision bigint NOT NULL
);

CREATE INDEX IF NOT EXISTS cursos_empresa_idx ON cursos(empresa_codigo);
